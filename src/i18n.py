def t(key: str, language: str = DEFAULT_LANGUAGE, **kwargs: object) -> str:
    """Translate ``key`` into ``language`` (English is the fallback).

    Unknown keys return the key itself so a missing string can never crash a
    page during a demo.
    """
    table = _STRINGS.get(language, _STRINGS[DEFAULT_LANGUAGE])
    text = table.get(key) or _STRINGS[DEFAULT_LANGUAGE].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text
